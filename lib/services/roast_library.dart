  /// Canonical normalization of language strings.
  static String normalizeLanguage(String? lang) {
    if (lang == null || lang.trim().isEmpty) return 'English';
    final lower = lang.trim().toLowerCase();
    if (lower.contains('tamil') || lower == 'ta') return 'Tamil';
    if (lower.contains('hindi') || lower == 'hi') return 'Hindi';
    if (lower.contains('telugu') || lower == 'te') return 'Telugu';
    if (lower.contains('kannada') || lower == 'kn') return 'Kannada';
    if (lower.contains('malayalam') || lower == 'ml') return 'Malayalam';
    return 'English';
  }

  /// Returns all 25 roasts for a given language.
  static List<RoastItem> getRoastsForLanguage(String language) {
    final canon = normalizeLanguage(language);
    return allRoasts.where((r) => r.language == canon).toList();
  }

  /// Returns onboarding roast for a given language.
  static RoastItem getOnboardingRoast(String language) {
    final canon = normalizeLanguage(language);
    return allRoasts.firstWhere(
      (r) => r.language == canon && r.situation == RoastCategory.newUserEmpty,
      orElse: () => allRoasts.firstWhere((r) => r.language == 'English'),
    );
  }

  /// Returns insufficient history roast for a given language.
  static RoastItem getInsufficientHistoryRoast(String language) {
    final canon = normalizeLanguage(language);
    return allRoasts.firstWhere(
      (r) => r.language == canon && r.situation == RoastCategory.insufficientHistory,
      orElse: () => allRoasts.firstWhere((r) => r.language == 'English'),
    );
  }
